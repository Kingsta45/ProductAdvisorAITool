        outer.pack(fill="both", expand=True, padx=28, pady=(0, 22))

        log_card = card(outer, height=130)
        log_card.pack(fill="x", pady=(0, 12))
        log_card.pack_propagate(False)
        section_label(log_card, "⚙  Progress").pack(anchor="w", padx=16, pady=(12, 4))
