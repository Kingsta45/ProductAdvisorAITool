#!/usr/bin/env python3
"""
Product-Fit Advisor -- GUI (v3, company-agnostic)
=================================================
A desktop form for advisor.py. Enter a prospect and get a pre-meeting brief
recommending which of your products to pitch.

INSTALL (on top of advisor.py's own deps):
    pip install customtkinter pillow

RUN:
    python gui.py

Keep gui.py, advisor.py, deepseek.env and the profiles/ folder together. The
product profile is loaded automatically from profiles/ (see profiles/my_fund.json;
if you keep several, set ADVISOR_PROFILE in deepseek.env). Analysis always uses
deepseek-v4-flash. Optional logos live in ./assets/ -- a profile can set "logo": "assets/x.png",
or name the file <company_slug>_logo.png / <company_slug>.png.
"""

