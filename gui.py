class QueueWriter:
    """Redirects advisor.py's print() calls into the GUI's log box."""
    def __init__(self, q):
        self.q = q

    def write(self, text):
        if text.strip():
            self.q.put(("log", text.rstrip("\n")))

    def flush(self):
        pass


def card(parent, **kwargs):
    defaults = dict(fg_color=BG_CARD, corner_radius=14, border_width=1, border_color=BORDER)
    defaults.update(kwargs)
    return ctk.CTkFrame(parent, **defaults)


def section_label(parent, text):
    return ctk.CTkLabel(
        parent, text=text.upper(),
        font=ctk.CTkFont(family=FONT_FAMILY, size=11, weight="bold"),
        text_color=TEXT_FAINT,
    )


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


# ── line classification for highlighting ───────────────────────────────────
_DIVIDER_RE = re.compile(r'^[=\-─]{5,}$')
_HEADER_RE = re.compile(r'^[A-Z][A-Z0-9 ()/\-]{4,}$')
_SCORE_LINE_RE = re.compile(r'^\s*\[[█░]+\]\s*\d+/100')


def _classify_report_line(line: str):
    s = line.strip()
    if not s:
        return None
    if _DIVIDER_RE.match(s):
        return "divider"
    if s.startswith("RECOMMENDED:") or s.startswith("Score:"):
        return "recommended"
    if _SCORE_LINE_RE.match(s):
        return "score"
    if s.startswith("+ "):
        return "plus"
    if s.startswith("- "):
        return "minus"
    if s.startswith("? "):
        return "gap"
    if s.startswith("Generated by") or s.startswith("Pre-meeting prep"):
        return "faint"
    if _HEADER_RE.match(s) and len(s.split()) <= 8:
        return "h1"
    return None


def _classify_log_line(line: str):
    s = line.strip()
    if not s:
        return None
    if "FAILED" in s:
        return "bad"
    if s.startswith("->") or s.startswith("Batch complete") or "Scraped" in s:
        return "good"
    if _DIVIDER_RE.match(s):
        return "faint"
    if "Analyzing with" in s:
        return "accent"
    return None


class AdvisorGUI(ctk.CTk):
    def __init__(self):
        super().__init__()
        self.geometry("900x900")
        self.minsize(780, 700)
        self.configure(fg_color=BG_MAIN)

        self.result_queue = queue.Queue()
        self.worker_thread = None
        self.last_report_text = ""
        self.last_analysis = None
        self.last_name = ""
        self.last_profile = None

        self.profile = None            # currently selected, validated profile dict
        self.logo_label = None

        self._build_header()
        self._build_input_card()
        self._build_output()
        self.report_callback_exception = self._on_callback_error
        self._load_default_profile(quiet=True)

        self.after(100, self._poll_queue)

    def _on_callback_error(self, exc, val, tb):
        """Tk swallows errors raised inside button callbacks; show them instead."""
        import traceback
        detail = "".join(traceback.format_exception(exc, val, tb))
        print(detail, file=sys.__stderr__)
        self._set_status("error")
        self.run_btn.configure(state="normal")
        messagebox.showerror("Unexpected error", f"{val}\n\n{detail[-800:]}")

    # ── header ──────────────────────────────────────────────────────────
    def _build_header(self):
        self.header = ctk.CTkFrame(self, fg_color="transparent")
        self.header.pack(fill="x", padx=28, pady=(24, 10))

        self.title_box = ctk.CTkFrame(self.header, fg_color="transparent")
        self.title_box.pack(side="left", fill="y")
        self.title_label = ctk.CTkLabel(
            self.title_box, text="Product-Fit Advisor",
            font=ctk.CTkFont(family=FONT_FAMILY, size=22, weight="bold"), text_color=TEXT_MAIN,
        )
        self.title_label.pack(anchor="w")
        self.subtitle_label = ctk.CTkLabel(
            self.title_box, text="Pre-meeting research for prospective investors",
            font=ctk.CTkFont(family=FONT_FAMILY, size=12), text_color=TEXT_SUB,
        )
        self.subtitle_label.pack(anchor="w")

        status_box = ctk.CTkFrame(self.header, fg_color="transparent")
        status_box.pack(side="right", anchor="e")
        self.status_badge = ctk.CTkFrame(status_box, fg_color=STATUS_COLORS["ready"][1], corner_radius=999)
        self.status_badge.pack(side="right")
        self.status_dot = ctk.CTkLabel(
            self.status_badge, text="●", font=ctk.CTkFont(size=11),
            text_color=STATUS_COLORS["ready"][0],
        )
        self.status_dot.pack(side="left", padx=(12, 5), pady=5)
        self.status_label = ctk.CTkLabel(
            self.status_badge, text=STATUS_COLORS["ready"][2],
            font=ctk.CTkFont(family=FONT_FAMILY, size=12, weight="bold"), text_color=TEXT_SUB,
        )
        self.status_label.pack(side="left", padx=(0, 14), pady=5)

        ctk.CTkFrame(self, fg_color=BORDER, height=1, corner_radius=0).pack(fill="x", padx=28, pady=(4, 0))

    def _set_status(self, state: str):
        color, bg, label = STATUS_COLORS[state]
        self.status_badge.configure(fg_color=bg)
        self.status_dot.configure(text_color=color)
        self.status_label.configure(text=label, text_color=color if state != "ready" else TEXT_SUB)

    def _find_logo(self, profile: dict):
        candidates = []
        if profile.get("logo"):
            candidates.append(SCRIPT_DIR / profile["logo"])
        slug = _slug(profile["company"])
        candidates += [ASSETS_DIR / f"{slug}_logo.png", ASSETS_DIR / f"{slug}.png"]
        return next((p for p in candidates if p.is_file()), None)

    def _set_logo(self, profile):
        if self.logo_label is not None:
            self.logo_label.destroy()
            self.logo_label = None
        if not (HAS_PIL and profile):
            return
        path = self._find_logo(profile)
        if not path:
            return
        try:
            img = Image.open(path)
            h = 42
            w = int(h * img.width / img.height)
            ctk_img = ctk.CTkImage(light_image=img, dark_image=img, size=(w, h))
            self.logo_label = ctk.CTkLabel(self.header, image=ctk_img, text="")
            self.logo_label.pack(side="left", padx=(0, 14), before=self.title_box)
        except Exception:
            self.logo_label = None

    # ── input card ──────────────────────────────────────────────────────
    def _build_input_card(self):
        outer = card(self)
        outer.pack(fill="x", padx=28, pady=(0, 14))
        parent = ctk.CTkFrame(outer, fg_color="transparent")
        parent.pack(fill="x", padx=20, pady=16)
        parent.columnconfigure(1, weight=1)

        label_font = ctk.CTkFont(family=FONT_FAMILY, size=13)
        hint_font = ctk.CTkFont(family=FONT_FAMILY, size=11)

        # Row 0: prospect name
        self.name_var = ctk.StringVar()
        ctk.CTkLabel(parent, text="Prospect name *", font=label_font, text_color=TEXT_MAIN
                     ).grid(row=0, column=0, sticky="w", padx=(4, 12), pady=8)
        ctk.CTkEntry(
            parent, textvariable=self.name_var, placeholder_text="e.g. Raffles Family Office",
            height=36, corner_radius=8, border_color=BORDER, fg_color=BG_MAIN,
        ).grid(row=0, column=1, sticky="ew", pady=8)

        # Row 1-2: website URLs (optional)
        ctk.CTkLabel(parent, text="Website URL(s)", font=label_font, text_color=TEXT_MAIN
                     ).grid(row=1, column=0, sticky="nw", padx=(4, 12), pady=(8, 8))
        self.website_box = ctk.CTkTextbox(
            parent, height=64, corner_radius=8, border_width=1, border_color=BORDER,
            fg_color=BG_MAIN, text_color=TEXT_MAIN, font=ctk.CTkFont(family=MONO_FAMILY, size=12), wrap="word",
        )
        self.website_box.grid(row=1, column=1, sticky="ew", pady=8)
        ctk.CTkLabel(
            parent, text="One URL per line (e.g. homepage + a team/strategy page). Leave blank to auto-search by name.",
            font=hint_font, text_color=TEXT_FAINT,
        ).grid(row=2, column=1, sticky="w", pady=(0, 8))

        # Row 3: run
        self.run_btn = ctk.CTkButton(
            parent, text="▶  Run Analysis", command=self._run_single, height=38, corner_radius=8,
            fg_color=ACCENT, hover_color=ACCENT_HOVER,
            font=ctk.CTkFont(family=FONT_FAMILY, size=13, weight="bold"),
        )
        self.run_btn.grid(row=3, column=1, sticky="e", pady=(8, 4))

    # ── profile handling (automatic) ────────────────────────────────────
    def _load_default_profile(self, quiet: bool = False) -> bool:
        """Load the product profile from profiles/ (or $ADVISOR_PROFILE). Returns True on success."""
        try:
            path = advisor.resolve_profile_path()
            self._apply_profile(advisor.load_profile(path))
            self._insert_log_line(f"Loaded product profile: {self.profile['company']} ({Path(path).name})")
            return True
        except advisor.ProfileError as e:
            self._apply_profile(None)
            self._insert_log_line(f"FAILED to load product profile: {e}")
            if not quiet:
                messagebox.showerror("Can't load product profile", str(e))
            return False

    def _apply_profile(self, profile):
        self.profile = profile
        if profile:
            company = profile["company"]
            self.title(f"{company} -- Product-Fit Advisor")
            self.subtitle_label.configure(text=f"Pre-meeting research for {company}'s prospective investors")
        else:
            self.title("Product-Fit Advisor")
            self.subtitle_label.configure(text="No product profile loaded")
        self._set_logo(profile)

